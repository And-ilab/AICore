from __future__ import annotations

from typing import Any

DEFAULT_SYSTEM_PROMPT = (
    "Ты суфлёр оператора контакт-центра Беларусбанка. "
    "Веди диалог строго по карте сценария. Пиши только на грамотном русском. "
    "Не выдумывай тарифы, сроки и условия, которых нет в тексте узла. "
    "Формулируй готовые фразы, которые оператор может сказать клиенту."
)


def n(
    node_id: str,
    node_type: str,
    label: str,
    *,
    hint: str = "",
    clarify: str = "",
    examples: list[str] | None = None,
    edges: list[dict[str, Any]] | None = None,
    intent: str = "",
) -> dict[str, Any]:
    return {
        "id": node_id,
        "type": node_type,
        "label": label,
        "hint_text": hint,
        "clarify_text": clarify,
        "examples": list(examples or []),
        "intent_id": intent,
        "edges": list(edges or []),
    }


def e(
    to: str,
    label: str,
    *keywords: str,
    reply: str,
    is_fallback: bool = False,
) -> dict[str, Any]:
    payload = {
        "to": to,
        "label": label,
        "reply": reply,
        "keywords": list(keywords),
    }
    if is_fallback:
        payload["is_fallback"] = True
    return payload


def scenario(
    code: str,
    title: str,
    root_question: str,
    nodes: list[dict[str, Any]],
    *,
    status: str = "production",
    channels: str = "both",
    system_prompt: str = DEFAULT_SYSTEM_PROMPT,
) -> dict[str, Any]:
    return {
        "code": code,
        "title": title,
        "root_question": root_question,
        "status": status,
        "channels": channels,
        "system_prompt": system_prompt,
        "graph": {"nodes": nodes},
    }


def linear_draft(
    code: str,
    title: str,
    root: str,
    examples: list[str],
    clarify: str,
    answer: str,
    *keywords: str,
    reply: str = "",
) -> dict[str, Any]:
    return scenario(
        code,
        title,
        root,
        [
            n(
                "start",
                "start",
                title,
                examples=examples,
                clarify=clarify,
                intent=code,
                edges=[
                    e(
                        "answer",
                        "Уточнение получено",
                        *keywords,
                        reply=reply or examples[0],
                    )
                ],
            ),
            n("answer", "answer", "Готовый ответ", hint=answer),
        ],
        status="draft",
    )


